encoding = QuantumCircuit(10)

# Position superposition
encoding.h([8, 9])

# Encode each pixel
for y in range(2):
    for x in range(2):
        binary = format(image[y][x], "08b")

        # Convert the selected position to controls |11>
        if y == 0:
            encoding.x(9)
        if x == 0:
            encoding.x(8)

        # Write the intensity bits
        for bit_index, bit in enumerate(binary):
            if bit == "1":
                target = 7 - bit_index
                encoding.mcx([9, 8], target)

        # Restore position
        if x == 0:
            encoding.x(8)
        if y == 0:
            encoding.x(9)

