from qiskit import QuantumCircuit

def diffuser():
    qc = QuantumCircuit(2)

    qc.h([0, 1])
    qc.x([0, 1])

    # Phase-flip |11>
    qc.cz(0, 1)

    qc.x([0, 1])
    qc.h([0, 1])

    return qc

diff = diffuser()
print(diff.draw(output="text"))

from qiskit.quantum_info import Statevector

initial_state = Statevector.from_label("++")
after_oracle = initial_state.evolve(oracle)
after_diffuser = after_oracle.evolve(diff)

print("After oracle:")
print(after_oracle.data)

print("\nAfter diffuser:")
